// Copies the server's device catalog into the demo: node tools/sync-catalog.mjs [--check] <catalog.json>
//   Writes js/custom/catalog.data.js (never edit it by hand). With --check it writes nothing and exits 1 if the file differs.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const check = args.includes('--check');
const src = args.find((a) => !a.startsWith('--'));
if (!src) { console.error('usage: node tools/sync-catalog.mjs [--check] <catalog.json>'); process.exit(2); }

const HEADER = '// Generated by tools/sync-catalog.mjs from live/src/NcbLive.Core/Scenes/catalog.json. Do not edit.\n';
let json;
try { json = JSON.parse(readFileSync(src, 'utf8').replace(/^﻿/, '')); } catch (e) { console.error(`cannot read ${src}: ${e.message}`); process.exit(2); }
const out = `${HEADER}export default ${JSON.stringify(json, null, 2)};\n`;
const dest = fileURLToPath(new URL('../js/custom/catalog.data.js', import.meta.url));

if (check) {
  const have = existsSync(dest) ? readFileSync(dest, 'utf8').replace(/\r\n/g, '\n') : null;
  if (have !== out) { console.error('js/custom/catalog.data.js differs from the server catalog: run node tools/sync-catalog.mjs <catalog.json>'); process.exit(1); }
  console.log('catalog copy matches');
} else {
  writeFileSync(dest, out);
  console.log(`wrote js/custom/catalog.data.js (${json.types?.length ?? 0} types)`);
}
